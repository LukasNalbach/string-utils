#ifndef STRING_UTILS_MISC_REPETITIVE_INPUT_HPP
#define STRING_UTILS_MISC_REPETITIVE_INPUT_HPP

#include <algorithm>
#include <cstdint>
#include <limits>
#include <random>
#include <string>
#include <vector>

/** @brief the kinds of repetitive sequences generated by generate_repetitive_input */
enum repetitive_input_kind_t : uint8_t {
    // a random base string, repeated exactly
    _repetitive_periodic = 0,
    // copies of a random base string, in which random symbols are replaced
    _repetitive_versioned = 1,
    // copies of a random base string, in which random symbols are inserted and deleted
    _repetitive_indel = 2,
    // copies of a random base string, each with its blocks in a random order
    _repetitive_blockmove = 3,
    // blocks of random symbols, alternating at random with copies of earlier substrings
    _repetitive_random_copies = 4,
    // each step appends a random symbol or (with a probability of 98 %) a copy of an earlier substring
    _repetitive_lz = 5,
    // the Fibonacci word over the symbols min_sym and min_sym + 1
    _repetitive_fibonacci = 6,
    // the number of kinds
    _repetitive_num_kinds = 7
};

// returns the name of a kind of repetitive sequence
inline std::string_view repetitiveness_kind_name(repetitive_input_kind_t kind)
{
    switch (kind) {
        case _repetitive_periodic: return "periodic";
        case _repetitive_versioned: return "versioned";
        case _repetitive_indel: return "indel";
        case _repetitive_blockmove: return "blockmove";
        case _repetitive_random_copies: return "markov";
        case _repetitive_lz: return "lz";
        default: return "fibonacci";
    }
}

// parameters of generate_repetitive_input; for the kinds that repeat a base string, n/r is roughly
// size / base_length
struct repetitive_params_t {
    repetitive_input_kind_t kind = _repetitive_versioned;
    uint64_t size = 1 << 20;      // n, the length of the sequence to generate
    uint64_t base_length = 4096;  // length of the base string (random copies, lz: maximum length of a copy)
    uint64_t block_length = 256;  // length of the blocks permuted by blockmove
    double mutation_rate = 0.001; // probability of an edit per position (versioned, indel)
    uint64_t seed = 0;            // seed of the random number generator (0: a random seed is used)
};

/**
 * @brief generates a repetitive sequence
 * @tparam inp_t sequence type to generate (e.g. std::string or std::vector<int32_t>)
 * @param params kind, length and repetitiveness of the sequence (see repetitive_params_t)
 * @param min_sym smallest symbol value that may occur
 * @param max_sym largest symbol value that may occur
 * @return the generated sequence
 */
template <typename inp_t>
inline inp_t generate_repetitive_input(
    repetitive_params_t params,
    typename inp_t::value_type min_sym = std::numeric_limits<typename inp_t::value_type>::min(),
    typename inp_t::value_type max_sym = std::numeric_limits<typename inp_t::value_type>::max())
{
    using sym_t = typename inp_t::value_type;
    // integer type of the symbol distribution (std::uniform_int_distribution does not support one-byte types)
    using dist_t = std::conditional_t<sizeof(sym_t) == 1,
        std::conditional_t<std::is_signed_v<sym_t>, int32_t, uint32_t>, sym_t>;

    std::random_device device;
    std::mt19937_64 random(params.seed == 0 ? device() : params.seed);
    std::uniform_int_distribution<dist_t> symbols(min_sym, max_sym);
    std::uniform_real_distribution<double> chance(0.0, 1.0);

    params.size = std::max<uint64_t>(1, params.size);
    params.base_length = std::clamp<uint64_t>(params.base_length, 1, params.size);
    params.block_length = std::clamp<uint64_t>(params.block_length, 1, params.base_length);

    inp_t input;
    input.reserve(params.size);
    auto draw = [&]() { return sym_t(symbols(random)); };

    if (params.kind == _repetitive_fibonacci) {
        inp_t previous, current;
        previous.push_back(sym_t(min_sym));
        current.push_back(sym_t(max_sym == min_sym ? min_sym : min_sym + 1));

        while (current.size() < params.size) {
            inp_t next = current;
            next.insert(next.end(), previous.begin(), previous.end());
            previous = std::move(current);
            current = std::move(next);
        }

        current.resize(params.size);
        return current;
    }

    if (params.kind == _repetitive_random_copies) {
        // minimum length of a copy and length of a block of random symbols
        uint64_t min_len = std::max<uint64_t>(1, params.base_length / 4);

        while (input.size() < params.size) {
            if (input.size() > params.base_length && chance(random) < 0.5) {
                std::uniform_int_distribution<uint64_t> from(0, input.size() - params.base_length - 1);
                std::uniform_int_distribution<uint64_t> length(min_len, params.base_length);
                uint64_t beg = from(random);
                uint64_t len = std::min(length(random), params.size - input.size());
                input.insert(input.end(), input.begin() + beg, input.begin() + beg + len);
            } else {
                for (uint64_t i = 0; i < min_len && input.size() < params.size; i++)
                    input.push_back(draw());
            }
        }

        input.resize(params.size);
        return input;
    }

    if (params.kind == _repetitive_lz) {
        input.push_back(draw());
        std::uniform_int_distribution<uint64_t> length(1, params.base_length);

        while (input.size() < params.size) {
            if (chance(random) < 0.98) {
                std::uniform_int_distribution<uint64_t> from(0, input.size() - 1);
                uint64_t beg = from(random);
                uint64_t len = std::min({ length(random), input.size() - beg,
                    params.size - input.size() });
                input.insert(input.end(), input.begin() + beg, input.begin() + beg + len);
            } else {
                input.push_back(draw());
            }
        }

        input.resize(params.size);
        return input;
    }

    // periodic, versioned, indel and blockmove: generate a random base string and append copies of it
    inp_t base;
    base.reserve(params.base_length);
    for (uint64_t i = 0; i < params.base_length; i++) base.push_back(draw());

    while (input.size() < params.size) {
        switch (params.kind) {
            case _repetitive_periodic:
                input.insert(input.end(), base.begin(),
                    base.begin() + std::min<uint64_t>(base.size(), params.size - input.size()));
                break;

            case _repetitive_versioned:
                for (uint64_t i = 0; i < base.size() && input.size() < params.size; i++)
                    input.push_back(chance(random) < params.mutation_rate ? draw() : base[i]);

                break;

            case _repetitive_indel:
                for (uint64_t i = 0; i < base.size() && input.size() < params.size; i++) {
                    double roll = chance(random);
                    if (roll < params.mutation_rate / 2) continue;               // deletion
                    if (roll < params.mutation_rate) input.push_back(draw());    // insertion
                    input.push_back(base[i]);
                }

                break;

            default: { // blockmove
                uint64_t num_blocks = std::max<uint64_t>(1, base.size() / params.block_length);
                std::vector<uint64_t> order(num_blocks);
                for (uint64_t i = 0; i < num_blocks; i++) order[i] = i;
                std::shuffle(order.begin(), order.end(), random);

                for (uint64_t block : order) {
                    if (input.size() >= params.size) break;
                    uint64_t beg = block * params.block_length;
                    uint64_t len = std::min({ params.block_length, base.size() - beg,
                        params.size - input.size() });
                    input.insert(input.end(), base.begin() + beg, base.begin() + beg + len);
                }

                break;
            }
        }
    }

    input.resize(params.size);
    return input;
}

/**
 * @brief draws random parameters for generate_repetitive_input (each kind with the same probability)
 * @tparam rng_t random number generator type
 * @param size length of the sequence to generate
 * @param random random number generator
 * @return the drawn parameters
 */
template <typename rng_t>
inline repetitive_params_t random_repetitive_params(uint64_t size, rng_t& random)
{
    std::uniform_int_distribution<uint32_t> kinds(0, _repetitive_num_kinds - 1);
    std::uniform_real_distribution<double> chance(0.0, 1.0);
    repetitive_params_t params;

    params.kind = repetitive_input_kind_t(kinds(random));
    params.size = size;

    // the base length: a number drawn from [1, size], divided by a number drawn from [1, 64]
    std::uniform_int_distribution<uint64_t> bases(1, std::max<uint64_t>(1, size));
    params.base_length = std::max<uint64_t>(1, bases(random) / std::uniform_int_distribution<uint64_t>(1, 64)(random));
    // the block length: the base length, divided by a number drawn from [1, _repetitive_num_kinds]
    params.block_length = std::max<uint64_t>(1, params.base_length / (1 + kinds(random)));
    params.mutation_rate = chance(random) * 0.05;
    params.seed = std::uniform_int_distribution<uint64_t>(1, ~uint64_t(0))(random);

    return params;
}

#endif // STRING_UTILS_MISC_REPETITIVE_INPUT_HPP
